/**
 * Bakes a land/ocean bitmask out of Natural Earth data.
 *
 * The globe needs to know which points on the sphere are land so it can
 * place dots there. Doing that in the browser would mean shipping and
 * parsing TopoJSON at runtime; instead this script rasterises the land
 * polygons once, at build time, into a packed bit array and writes a
 * small ES module the page can import directly.
 *
 * Rasterisation uses an even-odd scanline fill, which handles holes
 * (inland seas) correctly without a separate winding pass.
 *
 *   node tools/build-land-mask.mjs
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import * as topojson from "topojson-client";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, "..");

// 50m gives clean coastlines at the dot density the globe uses;
// 110m loses the Gulf and the Red Sea, which read as errors.
const SRC = resolve(ROOT, "node_modules/world-atlas/land-50m.json");
const OUT = resolve(ROOT, "src/js/webgl/land-mask.js");

const W = 1024;
const H = 512;

const topo = JSON.parse(readFileSync(SRC, "utf8"));
const land = topojson.feature(topo, topo.objects.land);

/** Collects every linear ring across every polygon in the feature set. */
function collectRings(geojson) {
  const rings = [];

  const addPolygon = (poly) => poly.forEach((ring) => rings.push(ring));

  const walk = (geom) => {
    if (!geom) return;
    if (geom.type === "Polygon") addPolygon(geom.coordinates);
    else if (geom.type === "MultiPolygon") geom.coordinates.forEach(addPolygon);
    else if (geom.type === "GeometryCollection") geom.geometries.forEach(walk);
  };

  if (geojson.type === "FeatureCollection") {
    geojson.features.forEach((f) => walk(f.geometry));
  } else {
    walk(geojson.geometry || geojson);
  }

  return rings;
}

const rings = collectRings(land);
console.log(`rings: ${rings.length}`);

// Project lon/lat to pixel space once, so the scanline loop is pure math.
const projected = rings.map((ring) =>
  ring.map(([lon, lat]) => [((lon + 180) / 360) * W, ((90 - lat) / 180) * H])
);

// Build edge lists bucketed by the scanlines they span — without this the
// fill is O(rows x edges) and takes minutes at this resolution.
const buckets = Array.from({ length: H }, () => []);

for (const ring of projected) {
  for (let i = 0; i < ring.length - 1; i++) {
    const [x1, y1] = ring[i];
    const [x2, y2] = ring[i + 1];
    if (y1 === y2) continue; // horizontal edges contribute nothing

    const yTop = Math.min(y1, y2);
    const yBot = Math.max(y1, y2);
    const rowStart = Math.max(0, Math.ceil(yTop - 0.5));
    const rowEnd = Math.min(H - 1, Math.floor(yBot - 0.5));

    for (let row = rowStart; row <= rowEnd; row++) {
      buckets[row].push([x1, y1, x2, y2]);
    }
  }
}

const bytes = new Uint8Array((W * H) / 8);

for (let row = 0; row < H; row++) {
  const y = row + 0.5;
  const xs = [];

  for (const [x1, y1, x2, y2] of buckets[row]) {
    // Half-open test on y avoids double-counting shared vertices.
    if (y >= Math.min(y1, y2) && y < Math.max(y1, y2)) {
      xs.push(x1 + ((y - y1) / (y2 - y1)) * (x2 - x1));
    }
  }

  if (!xs.length) continue;
  xs.sort((a, b) => a - b);

  for (let i = 0; i + 1 < xs.length; i += 2) {
    const from = Math.max(0, Math.ceil(xs[i] - 0.5));
    const to = Math.min(W - 1, Math.floor(xs[i + 1] - 0.5));
    for (let x = from; x <= to; x++) {
      const bit = row * W + x;
      bytes[bit >> 3] |= 128 >> (bit & 7);
    }
  }
}

let landCount = 0;
for (const b of bytes) landCount += (b.toString(2).match(/1/g) || []).length;
console.log(
  `land coverage: ${((landCount / (W * H)) * 100).toFixed(1)}%  (expect ~29%)`
);

const b64 = Buffer.from(bytes).toString("base64");

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(
  OUT,
  `/**
 * Land/ocean bitmask — generated by tools/build-land-mask.mjs
 * Source: Natural Earth 1:50m land via the world-atlas package.
 * ${W}x${H} equirectangular, 1 bit per cell, packed MSB-first, base64.
 * Do not edit by hand; re-run \`npm run mask\` instead.
 */
export const MASK_W = ${W};
export const MASK_H = ${H};

const PACKED =
  "${b64}";

const bytes = Uint8Array.from(atob(PACKED), (c) => c.charCodeAt(0));

/**
 * @param {number} lon degrees, -180..180
 * @param {number} lat degrees, -90..90
 * @returns {boolean} true when the coordinate falls on land
 */
export function isLand(lon, lat) {
  const x = Math.min(MASK_W - 1, Math.max(0, Math.floor(((lon + 180) / 360) * MASK_W)));
  const y = Math.min(MASK_H - 1, Math.max(0, Math.floor(((90 - lat) / 180) * MASK_H)));
  const bit = y * MASK_W + x;
  return (bytes[bit >> 3] & (128 >> (bit & 7))) !== 0;
}
`,
  "utf8"
);

console.log(`wrote ${OUT} (${(b64.length / 1024).toFixed(0)} KB base64)`);
